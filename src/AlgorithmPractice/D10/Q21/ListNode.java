package AlgorithmPractice.D10.Q21;

//https://leetcode-cn.com/problems/merge-two-sorted-lists/

public class ListNode {
    int val;
    ListNode next;

    ListNode()
    {

    }

    ListNode(int val)
    {
        this.val = val;
    }

    ListNode(int val, ListNode next)
    {
        this.val = val;
        this.next = next;
    }
}
