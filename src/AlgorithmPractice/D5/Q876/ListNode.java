package AlgorithmPractice.D5.Q876;

//https://leetcode-cn.com/problems/middle-of-the-linked-list/

public class ListNode {
    int val;
    ListNode next;

    ListNode()
    {

    }

    ListNode(int val)
    {
        this.val = val;
    }

    ListNode(int val, ListNode next)
    {
        this.val = val;
        this.next = next;
    }
}
